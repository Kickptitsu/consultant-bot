"""Грубое сравнение слов без ИИ: по нему ищет демо-режим и группирует вопросы /admin.

Слова сравниваются по началу («масла» = «масло», «работаете» = «работы») —
грубо, но для поиска раздела и подсказок админу хватает.
"""

import re

WORD_RE = re.compile(r"[a-zа-я0-9]+")

# Слова, которые есть почти в любом вопросе и ничего не говорят о теме
STOP_WORDS = {
    "как", "какой", "какая", "какие", "каким", "что", "чем", "где", "куда", "когда",
    "есть", "это", "этот", "для", "ваш", "ваши", "вас", "вам", "мне", "меня", "мой", "моя",
    "мою", "можно", "нужно", "надо", "или", "при", "без", "про", "так", "там", "тут", "уже",
    "еще", "очень", "пожалуйста", "подскажите", "скажите", "здравствуйте", "привет", "добрый",
    "хочу", "если", "чтобы", "будет", "могу", "можете", "его", "нее", "них", "все", "вообще",
    "сейчас", "тоже", "также", "только", "ним", "вы", "мы", "ли", "на", "по", "до", "от", "за",
    "не", "из", "во", "со", "об", "же", "бы", "ну", "нет", "да", "the",
}
# Слова о цене говорят, ЧТО спрашивают, но не О ЧЁМ
PRICE_WORDS = {"стоит", "стоимость", "цена", "цены", "почем", "прайс", "рублей", "сколько"}


def words(text: str) -> set[str]:
    """Значимые слова. Двухбуквенные тоже — иначе потеряется «ТО»."""
    text = text.lower().replace("ё", "е")
    text = re.sub(r"-(то|либо|нибудь)\b", "", text)   # «что-то» — не «ТО»
    return {word for word in WORD_RE.findall(text) if len(word) >= 2 and word not in STOP_WORDS}


def similar(a: str, b: str) -> bool:
    """Похожи ли слова: общее начало, отличаются только окончанием («масла» = «масло»)."""
    shortest = min(len(a), len(b))
    if shortest <= 3:
        return a == b
    common = 0
    for x, y in zip(a, b):
        if x != y:
            break
        common += 1
    if shortest == 4:
        return common >= 3
    return common >= 4 and common >= shortest - 3
